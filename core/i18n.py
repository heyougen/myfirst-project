_current_language = LANGUAGE_ZH_CN


def set_language(language: str) -> None:
    global _current_language
    if language in {LANGUAGE_ZH_CN, LANGUAGE_EN_US}:
        _current_language = language
    else:
        _current_language = LANGUAGE_ZH_CN


def get_language() -> str:
    return _current_language


def tr(text: str, **kwargs) -> str:
    if text is None:
        return ""
    template = text
    if _current_language == LANGUAGE_EN_US:
        template = TRANSLATIONS.get(text)
        if template is None:
            template = text
            # Runtime messages often contain paths, counts, branch names, or
            # Git output. Translate their known UI fragments without touching
            # the variable data.
            for source in sorted(TRANSLATIONS, key=len, reverse=True):
                if source in template:
                    template = template.replace(source, TRANSLATIONS[source])
    if kwargs:
        return template.format(**kwargs)
    return template


def tr_list(items):
    return [tr(item) for item in items]
